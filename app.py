import streamlit as strl
import numpy as np
import matplotlib.pyplot as plt

# Настройка страницы
strl.set_page_config(page_title="Биомеханика прыжка", layout="centered")

# Заголовок проекта
strl.title("🏃‍♂️ Цифровой биомеханический анализатор")
strl.subheader("Математическое моделирование прыжков в длину")

strl.write(
    "Этот интерактивный инструмент рассчитывает траекторию полета легкоатлета "
    "на основе законов баллистики. Изменяйте параметры разбега и отталкивания, "
    "чтобы найти оптимальный математический результат."
)

# Боковая панель для ввода данных (Интерактивные элементы)
strl.sidebar.header("⚙️ Параметры атлета")

# Скорость разбега (в м/с). У спринтеров она обычно от 8 до 11 м/с
v0 = strl.sidebar.slider(
    "Начальная скорость разбега (v₀, м/с):", 
    min_value=5.0, max_value=12.0, value=9.5, step=0.1
)

# Угол отталкивания (в градусах). В реальности оптимум около 20-25 градусов
alpha_deg = strl.sidebar.slider(
    "Угол отталкивания (α, градусы):", 
    min_value=10, max_value=45, value=22, step=1
)

# Константа ускорения свободного падения
g = 9.81

# Математические расчеты
alpha_rad = np.radians(alpha_deg) # Перевод угла в радианы для тригонометрии в Python

# Формула дальности полета тела: L = (v₀² * sin(2α)) / g
distance = (v0**2 * np.sin(2 * alpha_rad)) / g

# Формула максимальной высоты полета: H = (v₀² * sin²(α)) / (2g)
height = (v0**2 * (np.sin(alpha_rad))**2) / (2 * g)

# Вывод результатов на экран
strl.metric(label="📊 Рассчитанная дальность прыжка:", value=f"{distance:.2f} метров")
strl.write(f"🔝 Максимальная высота полета центра масс: **{height:.2f} м**")

# Построение графика траектории
strl.write("### 📈 Траектория полета спортсмена")

# Время полета: T = (2 * v₀ * sin(α)) / g
t_flight = (2 * v0 * np.sin(alpha_rad)) / g

# Генерируем точки времени от 0 до конца полета
t_points = np.linspace(0, t_flight, 100)

# Координаты X и Y в каждый момент времени
x_points = v0 * np.cos(alpha_rad) * t_points
y_points = v0 * np.sin(alpha_rad) * t_points - 0.5 * g * t_points**2

# Создаем красивый график с помощью matplotlib
fig, ax = plt.subplots(figsize=(8, 4))
ax.plot(x_points, y_points, color="#FF4B4B", linewidth=3, label="Траектория")
ax.fill_between(x_points, y_points, color="#FF4B4B", alpha=0.1) # Заливка под графиком

# Настройка осей и сетки
ax.set_xlim(0, max(10, distance + 1))
ax.set_ylim(0, max(2.5, height + 0.5))
ax.set_xlabel("Длина прыжка (метры)", fontsize=10)
ax.set_ylabel("Высота (метры)", fontsize=10)
ax.grid(True, linestyle="--", alpha=0.6)
ax.legend()

# Отображаем график в Streamlit
strl.pyplot(fig)

# Методическая справка для защиты проекта
strl.write("---")
strl.info(
    "💡 **Математическая справка для защиты:** "
    "Согласно чистой физике и математике, максимальная дальность полета достигается при угле 45°. "
    "Однако в легкой атлетике при угле 45° спортсмен потерял бы всю горизонтальную скорость разбега. "
    "Поэтому на практике золотая середина биомеханики — это угол **20–25 градусов** при максимальной скорости."
)
